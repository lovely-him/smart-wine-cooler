"""层内位置的次序：按框中心 x、再中心 y 从左到右。

位置不落库，也不许人工指定，所以这份次序必须只有一处实现——
推理、提交、位置历史三处若各写一份，迟早会给出不同的"第几个"。
"""


def key_xywh(box):
    """数据库与提交里的形状：{"x", "y", "w", "h"}（归一化）。"""
    return (box["x"] + box["w"] / 2, box["y"] + box["h"] / 2)


def key_ltrb(box):
    """检测器返回的形状：[x1, y1, x2, y2]（归一化）。"""
    return ((box[0] + box[2]) / 2, (box[1] + box[3]) / 2)
